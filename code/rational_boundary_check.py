"""Exact-rational validation of three previously flagged projection cases.

The represented inputs are exactly the binary64 values regenerated by the
recorded simulation and fitter. This is not a general floating-point proof.
"""
from fractions import Fraction as Q
from functools import lru_cache
from pathlib import Path
import hashlib, json, math, sys
import numpy as np
import pandas as pd
from threadpoolctl import threadpool_limits
from circular import moments
from certified_experiment import NAMES, draw
from certified_projection import fit
from fair_baselines import RGRID

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'results' / 'rational_boundary_check.json'
CASES = [('smooth', 500, 9, 3), ('bimodal', 500, 1, 6), ('zero_cardioid', 500, 4, 2)]
ETAS = [.02, .1, .5, 2.]
PI_LO = Q(3141592653589793238462643383279, 10**30)
PI_HI = PI_LO + Q(1, 10**30)
PI_MID = (PI_LO + PI_HI) / 2
EPS = Q(1, 10**23)

def arctan_bounds(d, n=40):
    s = sum((Q((-1)**k, (2*k+1)*d**(2*k+1)) for k in range(n)), Q())
    return s, s + Q(1, (2*n+1)*d**(2*n+1))

def verify_constants():
    a, b = arctan_bounds(5); c, d = arctan_bounds(239)
    # Machin identity and alternating series, n even.
    assert PI_LO < 16*a - 4*d and 16*b - 4*c < PI_HI
    assert (2*PI_HI)**52 / math.factorial(52) + (PI_HI-PI_LO) < EPS
    assert (2*PI_HI)**53 / math.factorial(53) + (PI_HI-PI_LO) < EPS

@lru_cache(maxsize=None)
def trig_pair(k, L):
    """Rational cosine and sine approximations with absolute error < EPS."""
    x = 2*PI_MID*Q(k % L, L)
    # 26 terms; the next terms bound Taylor remainders for x in [0, 2*pi].
    z = x*x
    cos = term_c = Q(1); sin = term_s = x
    for j in range(1, 26):
        term_c *= -z / ((2*j-1)*(2*j))
        term_s *= -z / ((2*j)*(2*j+1))
        cos += term_c; sin += term_s
    return cos, sin

def F(x):
    return Q.from_float(float(x))

def lower_q_at_nodes(coefs, L):
    magnitudes = sum((abs(re)+abs(im) for re,im in coefs), Q())
    allowance = 2*EPS*magnitudes
    lowest = None
    for k in range(L):
        value = Q(1)
        for ell,(re,im) in enumerate(coefs, 1):
            cs,sn = trig_pair((k*ell) % L, L)
            value += 2*(re*cs-im*sn)
        lower = value-allowance
        lowest = lower if lowest is None else min(lowest, lower)
    return lowest

def hexfloat(x):
    return float(x).hex()

def main():
    verify_constants()
    timings = pd.read_csv(ROOT/'results/precision_tradeoff/timings.csv')
    records = []
    for name,n,rep,r in CASES:
        rng=np.random.default_rng(np.random.SeedSequence([20261104,NAMES.index(name),n,rep]))
        c=moments(draw(name,n,rng),max(RGRID))
        coefs=[(F(v.real),F(v.imag)) for v in c[1:r+1]]
        # min q >= min-grid q - pi^2/L^2 * sum l^2 |a_l|.
        L=128
        grid_lower=lower_q_at_nodes(coefs,L)
        beta=PI_HI**2 / L**2 * sum((ell**2*(abs(re)+abs(im)) for ell,(re,im) in enumerate(coefs,1)),Q())
        continuous_lower=grid_lower-beta
        assert continuous_lower > 0
        for eta in ETAS:
            a,info=fit(c,r,n,eta=eta,max_ratio=256)
            D=int(info['D']); nodes=2*D+1
            outcoefs=[(F(v.real),F(v.imag)) for v in a[1:]]
            deconv=[(re*Q(D+1,D+1-ell),im*Q(D+1,D+1-ell)) for ell,(re,im) in enumerate(outcoefs,1)]
            inner_lower=lower_q_at_nodes(deconv,nodes)
            assert inner_lower > 0
            sqsum=sum(((re-c_re)**2+(im-c_im)**2 for (re,im),(c_re,c_im) in zip(outcoefs,coefs)),Q())
            err_upper=sqsum/PI_LO
            bound=F(info['l2_squared_bound'])
            assert err_upper < bound
            old=timings[(timings.scenario==name)&(timings.n==n)&(timings.rep==rep)&(timings.r==r)&(timings.eta==eta)]
            assert len(old)==1 and abs(old.l2_squared_bound.iloc[0]-info['l2_squared_bound'])<1e-15
            records.append({'scenario':name,'n':n,'rep':rep,'r':r,'eta':eta,'D':D,
                'continuous_density_lower':float(continuous_lower),
                'inner_node_slack_lower':float(inner_lower),
                'actual_squared_l2_upper':float(err_upper),'recorded_bound':float(bound),
                'bound_minus_upper_lower':float(bound-err_upper),
                'target_binary64_hex':[[hexfloat(v.real),hexfloat(v.imag)] for v in c[1:r+1]],
                'output_binary64_hex':[[hexfloat(v.real),hexfloat(v.imag)] for v in a[1:]],
                'bound_binary64_hex':hexfloat(info['l2_squared_bound'])})
    result={'passed':True,'arithmetic':'Python exact integers and fractions; rational Taylor/Machin bounds',
        'input_model':'Reconstructed binary64 coefficients treated as exact real numbers',
        'cases':len(CASES),'comparisons':len(records),'min_density_lower':min(x['continuous_density_lower'] for x in records),
        'min_inner_slack_lower':min(x['inner_node_slack_lower'] for x in records),
        'minimum_bound_margin':min(x['bound_minus_upper_lower'] for x in records),
        'timings_file_sha256':hashlib.sha256((ROOT/'results/precision_tradeoff/timings.csv').read_bytes()).hexdigest(),
        'details':records}
    if OUT.exists():
        if json.loads(OUT.read_text(encoding='utf-8')) != result:
            raise RuntimeError('Recomputed audit differs from the previous record; refusing to overwrite')
    else:
        OUT.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({k:v for k,v in result.items() if k!='details'},indent=2))

if __name__=='__main__':
    with threadpool_limits(limits=1): main()
